-- Analytics : une ligne par visite (premier chargement du site).
CREATE TABLE IF NOT EXISTS visits (
    id              INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    visited_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    ip              TEXT NOT NULL,
    country_code    CHAR(2),
    country_name    TEXT,
    city            TEXT,
    device          TEXT NOT NULL DEFAULT 'unknown' CHECK (device IN ('desktop', 'mobile', 'tablet', 'unknown')),
    browser         TEXT,
    os              TEXT,
    user_agent      TEXT,
    path            TEXT NOT NULL,
    referrer        TEXT,
    language        TEXT,
    timezone        TEXT,
    screen_width    SMALLINT,
    theme           TEXT,
    is_new_visitor  BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS visits_visited_at_idx ON visits (visited_at DESC);
CREATE INDEX IF NOT EXISTS visits_ip_idx ON visits (ip);
