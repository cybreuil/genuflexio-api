-- =========================================================
-- 1) Référentiels
-- =========================================================

-- Langues disponibles
CREATE TABLE locales (
    code TEXT PRIMARY KEY CHECK (char_length(code) <= 10),	-- ex: fr, en, la
    native_name TEXT NOT NULL,
    english_name TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

-- Calendriers liturgiques (avec héritage hiérarchique)
CREATE TABLE calendars (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    code TEXT UNIQUE NOT NULL,	-- ex: ROMAN_GENERAL, ROMAN_FRANCE, ORTHODOX_RUSSIAN etc
    parent_id INTEGER REFERENCES calendars(id) ON DELETE SET NULL,
    date_system TEXT NOT NULL DEFAULT 'gregorian' CHECK (date_system IN ('gregorian', 'julian')),	-- gregorian, julian
    easter_computation TEXT NOT NULL DEFAULT 'western' CHECK (easter_computation IN ('western', 'eastern')),	-- western, eastern
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Traductions des calendriers
CREATE TABLE calendar_translations (
	calendar_id INTEGER NOT NULL REFERENCES calendars(id) ON DELETE CASCADE,
	locale_code TEXT NOT NULL REFERENCES locales(code) ON DELETE CASCADE,
	name TEXT NOT NULL,
	description TEXT,
	PRIMARY KEY (calendar_id, locale_code)
);

-- Rangs liturgiques (dépendants du calendrier)
CREATE TABLE liturgical_ranks (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    calendar_id INTEGER NOT NULL REFERENCES calendars(id) ON DELETE CASCADE,
	code TEXT NOT NULL,	-- ex: Modern Roman: SOLEMNITY, FEAST, MEM_OBL, MEM_OPT, FERIA / Traditional: CLASS_I, CLASS_II, CLASS_III, CLASS_IV
    precedence SMALLINT NOT NULL CHECK (precedence > 0),
    UNIQUE (calendar_id, code),
    UNIQUE (calendar_id, precedence)
);

-- Traduction des rangs liturgiques
CREATE TABLE liturgical_rank_translations (
	rank_id INTEGER NOT NULL REFERENCES liturgical_ranks(id) ON DELETE CASCADE,
	locale_code TEXT NOT NULL REFERENCES locales(code) ON DELETE CASCADE,
	label TEXT NOT NULL,
	PRIMARY KEY (rank_id, locale_code)
);

-- Couleurs liturgiques
CREATE TABLE liturgical_colors (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    code TEXT UNIQUE NOT NULL,	-- ex: WHITE, RED, GREEN
    hex_color TEXT NOT NULL CHECK (hex_color ~ '^#[0-9A-Fa-f]{6}$')	-- ex: #FFFFFF, #FF0000
);

-- Traductions des couleurs liturgiques
CREATE TABLE liturgical_color_translations (
    color_id INTEGER NOT NULL REFERENCES liturgical_colors(id) ON DELETE CASCADE,
    locale_code TEXT NOT NULL REFERENCES locales(code) ON DELETE CASCADE,
    label TEXT NOT NULL,
    PRIMARY KEY (color_id, locale_code)
);

-- Lieux (normalisés)
CREATE TABLE places (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    code TEXT UNIQUE NOT NULL, 	-- ex: ROME, ASSISI, CLUNY
    country_code TEXT CHECK (country_code ~ '^[A-Z]{2}$'),	-- ex: IT, FR (optionnel)
    latitude DOUBLE PRECISION,	-- optionnel
    longitude DOUBLE PRECISION 	-- optionnel
);

-- Traductions des lieux
CREATE TABLE place_translations (
    place_id INTEGER NOT NULL REFERENCES places(id) ON DELETE CASCADE,
    locale_code TEXT NOT NULL REFERENCES locales(code) ON DELETE CASCADE,
    name TEXT NOT NULL,        -- ex: Rome / Roma
    description TEXT,          -- optionnel: contexte historique
    PRIMARY KEY (place_id, locale_code)
);

-- Temps liturgiques (référentiel)
CREATE TABLE liturgical_seasons (
    code TEXT PRIMARY KEY CHECK (code IN (
        'ADVENT',
        'CHRISTMASTIDE',
        'ORDINARY_TIME',
        'LENT',
        'TRIDUUM',
        'EASTERTIDE',
        -- Traditionnal extra :
        'THROUGHOUT_THE_YEAR',
        'CHRISTMAS',
        'EPIPHANY',
        'SEPTUAGESIMA',
        'PASSIONTIDE',
        'HOLY_WEEK',
        'PASCHALTIDE',
        'ASCENSIONTIDE',
        'PENTECOST_OCTAVE',
        'POST_PENTECOST'
    )),
    default_name TEXT NOT NULL
);

CREATE TABLE liturgical_season_translations (
    season_code TEXT NOT NULL REFERENCES liturgical_seasons(code) ON DELETE CASCADE,
    locale_code TEXT NOT NULL REFERENCES locales(code) ON DELETE CASCADE,
    label TEXT NOT NULL,
    PRIMARY KEY (season_code, locale_code)
);

-- rule-based boundaries for liturgical seasons (fixed or movable)
CREATE TABLE liturgical_season_intervals (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

    calendar_id INTEGER NOT NULL REFERENCES calendars(id) ON DELETE CASCADE,
    season_code TEXT NOT NULL REFERENCES liturgical_seasons(code) ON DELETE RESTRICT,

    segment_index SMALLINT NOT NULL DEFAULT 0,

    -- START
    start_kind TEXT NOT NULL CHECK (start_kind IN ('fixed', 'movable')),
    start_month SMALLINT CHECK (start_month BETWEEN 1 AND 12),
    start_day SMALLINT CHECK (start_day BETWEEN 1 AND 31),
    start_movable_base TEXT,
    start_offset_days SMALLINT DEFAULT 0,

    -- END
    end_kind TEXT NOT NULL CHECK (end_kind IN ('fixed', 'movable')),
    end_month SMALLINT CHECK (end_month BETWEEN 1 AND 12),
    end_day SMALLINT CHECK (end_day BETWEEN 1 AND 31),
    end_movable_base TEXT,
    end_offset_days SMALLINT DEFAULT 0,

    inclusive BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT,

    CHECK (
        (start_kind='fixed' AND start_month IS NOT NULL AND start_day IS NOT NULL AND start_movable_base IS NULL)
        OR
        (start_kind='movable' AND start_movable_base IS NOT NULL AND start_month IS NULL AND start_day IS NULL)
    ),

    CHECK (
        (end_kind='fixed' AND end_month IS NOT NULL AND end_day IS NOT NULL AND end_movable_base IS NULL)
        OR
        (end_kind='movable' AND end_movable_base IS NOT NULL AND end_month IS NULL AND end_day IS NULL)
    )
);

-- Couleur par défaut des temps liturgiques (fallback affichage)
-- Permet: celebration.color_id NULL => prendre la couleur de la saison
CREATE TABLE liturgical_season_colors (
    season_code TEXT NOT NULL REFERENCES liturgical_seasons(code) ON DELETE CASCADE,
    calendar_id INTEGER NOT NULL REFERENCES calendars(id) ON DELETE CASCADE,
    color_id INTEGER NOT NULL REFERENCES liturgical_colors(id) ON DELETE RESTRICT,
    PRIMARY KEY (season_code, calendar_id)
);


-- =========================================================
-- 2) Saints
-- =========================================================

CREATE TABLE saints (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    slug TEXT UNIQUE NOT NULL,	-- ex: saint-joseph
    default_name TEXT NOT NULL,
    birth_year SMALLINT,
    birth_month SMALLINT CHECK (birth_month BETWEEN 1 AND 12),
	birth_day SMALLINT CHECK (birth_day BETWEEN 1 AND 31),
	birth_is_approximate BOOLEAN NOT NULL DEFAULT FALSE,	-- true si la date de naissance est approximative (ex: "vers l'an 400'")
    death_year SMALLINT,
	death_month SMALLINT CHECK (death_month BETWEEN 1 AND 12),
	death_day SMALLINT CHECK (death_day BETWEEN 1 AND 31),
	death_is_approximate BOOLEAN NOT NULL DEFAULT FALSE,	-- true si la date de décès est approximative (ex: "vers l'an 500'")
    century SMALLINT CHECK (century > 0),	-- ex: 1 pour Ier siècle, 20 pour XXe siècle
    place_of_birth_id INTEGER REFERENCES places(id) ON DELETE SET NULL,
	place_of_death_id INTEGER REFERENCES places(id) ON DELETE SET NULL,
	place_of_activity_id INTEGER REFERENCES places(id) ON DELETE SET NULL,	-- lieu principal d'activité (ex: évêque de Rome -> place_of_activity = ROME)
    -- On gere desormais les images dans une table séparée saint_images pour permettre plusieurs images par saint et des métadonnées (crédit, licence, etc)
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Contraintes pour assurer la cohérence des dates (pas de jour sans mois)
    CONSTRAINT chk_saints_birth_day_month
        CHECK (birth_day IS NULL OR birth_month IS NOT NULL),

    CONSTRAINT chk_saints_death_day_month
        CHECK (death_day IS NULL OR death_month IS NOT NULL)
);

CREATE TABLE saint_translations (
    saint_id INTEGER NOT NULL REFERENCES saints(id) ON DELETE CASCADE,
    locale_code TEXT NOT NULL REFERENCES locales(code) ON DELETE CASCADE,
    name TEXT NOT NULL,
    short_description TEXT,
    full_biography TEXT,
    life_label TEXT,   -- C'est la date approximative ex: "Vers le IVe siècle"
    PRIMARY KEY (saint_id, locale_code)
);

-- =========================================================
-- 3) Images
-- =========================================================

-- Images / œuvres
-- Une image peut représenter plusieurs saints.
-- Les métadonnées propres à l'image sont stockées ici une seule fois.
CREATE TABLE images (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    image_url TEXT UNIQUE NOT NULL, -- ex: /saints/saint-joseph_guido-reni.jpg

    title TEXT NOT NULL,            -- titre de l'œuvre ou nom usuel
    image_type TEXT,                -- painting, icon, mosaic, fresco, photograph, engraving, illustration, stained_glass, etc.

    alt_text TEXT,                  -- description accessible par défaut
    caption TEXT,                   -- légende optionnelle affichable, si tu ne veux pas la générer côté front

    creator TEXT,                   -- peintre, photographe, graveur, atelier, etc.
    date_label TEXT,                -- ex: "XVIIe siècle", "vers 1500", "1610-1612"
    century INTEGER CHECK (century > 0),	-- ex: 17 pour XVIIe siècle
    repository TEXT,                -- lieu de conservation : musée, église, collection privée, bibliothèque...

    credit TEXT,
    license TEXT,
    source_url TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE saint_images (
    saint_id INTEGER NOT NULL REFERENCES saints(id) ON DELETE CASCADE,
    image_id INTEGER NOT NULL REFERENCES images(id) ON DELETE CASCADE,

    sort_order SMALLINT NOT NULL DEFAULT 1,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,

    subject_role TEXT NOT NULL DEFAULT 'subject',
    alt_text_override TEXT,
    caption_override TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    PRIMARY KEY (saint_id, image_id)
);

-- =========================================================
-- 4) Attributs (normalisés + traduits)
-- =========================================================

CREATE TABLE attributes (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    code TEXT UNIQUE NOT NULL, -- ex: LILY, SWORD, SKULL, BOOK
    category TEXT CHECK (category IN ('symbol', 'title', 'order')) -- ex: symbol, title, order
    -- symbol = attribut iconographique (ex: LILY, SWORD, SKULL, BOOK, etc )
    -- title = titre honorifique (ex: MARTYR, VIRGIN, CONFESSOR, DOCTOR_OF_THE_CHURCH, etc)
    -- Order = membre d'un ordre religieux (ex: BENEDICTINE, DOMINICAN, JESUIT etc)
);

CREATE TABLE attribute_translations (
    attribute_id INTEGER NOT NULL REFERENCES attributes(id) ON DELETE CASCADE,
    locale_code TEXT NOT NULL REFERENCES locales(code) ON DELETE CASCADE,
    label TEXT NOT NULL,
    description TEXT,
    PRIMARY KEY (attribute_id, locale_code)
);

CREATE TABLE saint_attributes (
    saint_id INTEGER NOT NULL REFERENCES saints(id) ON DELETE CASCADE,
    attribute_id INTEGER NOT NULL REFERENCES attributes(id) ON DELETE CASCADE,
    PRIMARY KEY (saint_id, attribute_id)
);

-- =========================================================
-- 5) Patronages (normalisés + traduits)
-- =========================================================

CREATE TABLE patronages (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    code TEXT UNIQUE NOT NULL -- ex: WORKERS, FRANCE, STUDENTS
);

CREATE TABLE patronage_translations (
    patronage_id INTEGER NOT NULL REFERENCES patronages(id) ON DELETE CASCADE,
    locale_code TEXT NOT NULL REFERENCES locales(code) ON DELETE CASCADE,
    label TEXT NOT NULL,
    description TEXT,
    PRIMARY KEY (patronage_id, locale_code)
);

CREATE TABLE saint_patronages (
    saint_id     INTEGER NOT NULL REFERENCES saints(id)    ON DELETE CASCADE,
    patronage_id INTEGER NOT NULL REFERENCES patronages(id) ON DELETE CASCADE,
    source_type  TEXT CHECK (source_type IN ('OFF', 'TRD', 'DEV')),
    -- OFF = proclamation officielle du Saint-Siège (Acta Apostolicae Sedis)
    -- TRD = patronage traditionnel séculaire reconnu
    -- DEV = dévotion populaire répandue
    PRIMARY KEY (saint_id, patronage_id)
);

-- =========================================================
-- 6) Fêtes liturgiques
-- =========================================================

CREATE TABLE feasts (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    slug TEXT UNIQUE NOT NULL, -- exemple: nativity-of-saint-john-the-baptist
    default_name TEXT NOT NULL,
    feast_type TEXT NOT NULL, -- ex: saint, marial, christologique, dedicace, autre ou en anglais: saint, marian, christological, dedication, other
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE feast_translations (
    feast_id INTEGER NOT NULL REFERENCES feasts(id) ON DELETE CASCADE,
    locale_code TEXT NOT NULL REFERENCES locales(code) ON DELETE CASCADE,
    name TEXT NOT NULL,
    description TEXT,
    PRIMARY KEY (feast_id, locale_code)
);

-- Liaison feats <-> saints
CREATE TABLE feast_saints (
	feast_id INTEGER NOT NULL REFERENCES feasts(id) ON DELETE CASCADE,
	saint_id INTEGER NOT NULL REFERENCES saints(id) ON DELETE CASCADE,
    role TEXT, -- ex: principal, compagnon, martyr
    PRIMARY KEY (feast_id, saint_id)
);

